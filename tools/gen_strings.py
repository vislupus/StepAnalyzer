#!/usr/bin/env python3
"""Generate strings.xml (en) and values-bg/strings.xml from tools/strings_src.py and verify
that every R.string reference in the Kotlin sources exists in both languages."""
import os
import re
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from strings_src import EN, BG  # noqa: E402

ROOT = os.path.join(HERE, "..", "app", "src", "main")


def android_escape(s):
    s = escape(s)
    s = s.replace("'", "\\'")
    return s


def write(path, table, lang_comment):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {lang_comment} Generated by tools/gen_strings.py from tools/strings_src.py - edit there. -->", "<resources>"]
    for key in table:
        value = table[key]
        attr = ' formatted="false"' if value.count("%") > 1 and "$" not in value else ""
        lines.append(f'    <string name="{key}"{attr}>{android_escape(value)}</string>')
    lines.append("</resources>")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def main():
    missing_bg = [k for k in EN if k not in BG]
    extra_bg = [k for k in BG if k not in EN]
    if missing_bg or extra_bg:
        print("key mismatch - missing in BG:", missing_bg, "extra in BG:", extra_bg)
        sys.exit(1)
    for k in EN:
        fe = sorted(re.findall(r"%\d\$[sd]", EN[k]))
        fb = sorted(re.findall(r"%\d\$[sd]", BG[k]))
        if fe != fb:
            print(f"format mismatch for {k}: {fe} vs {fb}")
            sys.exit(1)
    used = set()
    for dirpath, _, files in os.walk(os.path.join(ROOT, "java")):
        for f in files:
            if f.endswith(".kt"):
                with open(os.path.join(dirpath, f), encoding="utf-8") as fh:
                    used.update(re.findall(r"R\.string\.([a-z0-9_]+)", fh.read()))
    manifest = open(os.path.join(ROOT, "AndroidManifest.xml"), encoding="utf-8").read()
    used.update(re.findall(r"@string/([a-z0-9_]+)", manifest))
    undefined = sorted(k for k in used if k not in EN)
    if undefined:
        print("referenced but undefined:", undefined)
        sys.exit(1)
    unused = sorted(k for k in EN if k not in used)
    write(os.path.join(ROOT, "res", "values", "strings.xml"), EN, "English (default).")
    write(os.path.join(ROOT, "res", "values-bg", "strings.xml"), BG, "Bulgarian.")
    print(f"ok: {len(EN)} strings, {len(used)} referenced, unused: {unused}")


if __name__ == "__main__":
    main()
